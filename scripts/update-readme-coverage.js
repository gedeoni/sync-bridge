const fs = require('fs');
const path = require('path');

// Target thresholds:
// < 50% = red
// 50% - 70% = yellow
// > 70% = green
function getBadgeColor(percentage) {
  if (percentage < 50) return 'red';
  if (percentage <= 70) return 'yellow';
  return 'green';
}

function generateBadgeMarkdown(label, percentage) {
  const color = getBadgeColor(percentage);
  // Shields.io URL structure
  const url = `https://img.shields.io/badge/${encodeURIComponent(label)}-${percentage}%25-${color}`;
  return `![Coverage](${url})`;
}

// Helper to look up file recursively under a directory (useful for C# GUID folders)
function findFile(dir, fileNamePattern) {
  if (!fs.existsSync(dir)) return null;
  const files = fs.readdirSync(dir);
  for (const file of files) {
    const filePath = path.join(dir, file);
    const stat = fs.statSync(filePath);
    if (stat.isDirectory()) {
      const found = findFile(filePath, fileNamePattern);
      if (found) return found;
    } else if (fileNamePattern.test(file)) {
      return filePath;
    }
  }
  return null;
}

const parsers = {
  java: () => {
    const reportPath = path.join(__dirname, '../sync-bridge-java/target/site/jacoco/jacoco.xml');
    if (!fs.existsSync(reportPath)) return null;
    const xmlContent = fs.readFileSync(reportPath, 'utf8');
    // JaCoCo lists global line metrics at the end of the report
    const matches = [...xmlContent.matchAll(/<counter\s+type="LINE"\s+missed="(\d+)"\s+covered="(\d+)"\s*\/>/g)];
    if (matches.length > 0) {
      const lastMatch = matches[matches.length - 1];
      const missed = parseInt(lastMatch[1], 10);
      const covered = parseInt(lastMatch[2], 10);
      const total = missed + covered;
      return total > 0 ? Math.round((covered / total) * 100) : 0;
    }
    return null;
  },

  nestjs: () => {
    const reportPath = path.join(__dirname, '../sync-bridge-nestjs/coverage/coverage-summary.json');
    if (!fs.existsSync(reportPath)) return null;
    const data = JSON.parse(fs.readFileSync(reportPath, 'utf8'));
    return data.total && data.total.lines ? Math.round(data.total.lines.pct) : null;
  },

  express: () => {
    const reportPath = path.join(__dirname, '../sync-bridge-express/coverage/coverage-summary.json');
    if (!fs.existsSync(reportPath)) return null;
    const data = JSON.parse(fs.readFileSync(reportPath, 'utf8'));
    return data.total && data.total.lines ? Math.round(data.total.lines.pct) : null;
  },

  django: () => {
    const reportPath = path.join(__dirname, '../sync-bridge-django/coverage.json');
    if (!fs.existsSync(reportPath)) return null;
    const data = JSON.parse(fs.readFileSync(reportPath, 'utf8'));
    return data.totals ? Math.round(data.totals.percent_covered) : null;
  },

  rust: () => {
    // Check for both cargo-llvm-cov json output and tarpaulin JSON output
    const llvmReportPath = path.join(__dirname, '../sync-bridge-rust/coverage.json');
    if (fs.existsSync(llvmReportPath)) {
      const data = JSON.parse(fs.readFileSync(llvmReportPath, 'utf8'));
      if (data.data && data.data[0] && data.data[0].totals && data.data[0].totals.lines) {
        return Math.round(data.data[0].totals.lines.percent);
      }
    }

    const tarpReportPath = path.join(__dirname, '../sync-bridge-rust/tarpaulin-report.json');
    if (fs.existsSync(tarpReportPath)) {
      const data = JSON.parse(fs.readFileSync(tarpReportPath, 'utf8'));
      if (typeof data.coverage === 'number') {
        return Math.round(data.coverage);
      }
    }
    return null;
  },

  go: () => {
    const reportPath = path.join(__dirname, '../sync-bridge-go/coverage.out');
    if (!fs.existsSync(reportPath)) return null;
    const content = fs.readFileSync(reportPath, 'utf8');
    const lines = content.split('\n');
    let totalStatements = 0;
    let coveredStatements = 0;
    for (const line of lines) {
      if (line.startsWith('mode:') || !line.trim()) continue;
      const parts = line.trim().split(/\s+/);
      if (parts.length >= 3) {
        const numStatements = parseInt(parts[parts.length - 2], 10);
        const count = parseInt(parts[parts.length - 1], 10);
        if (!isNaN(numStatements) && !isNaN(count)) {
          totalStatements += numStatements;
          if (count > 0) {
            coveredStatements += numStatements;
          }
        }
      }
    }
    return totalStatements > 0 ? Math.round((coveredStatements / totalStatements) * 100) : null;
  },

  fastapi: () => {
    const reportPath = path.join(__dirname, '../sync-bridge-fastapi/coverage.json');
    if (!fs.existsSync(reportPath)) return null;
    const data = JSON.parse(fs.readFileSync(reportPath, 'utf8'));
    return data.totals ? Math.round(data.totals.percent_covered) : null;
  },

  csharp: () => {
    // Cobertura format generated by Coverlet
    const testsDir = path.join(__dirname, '../sync-bridge-csharp/SyncBridgeCsharp.Tests');
    const reportPath = findFile(testsDir, /coverage\.cobertura\.xml$/);
    if (!reportPath) return null;
    
    const xmlContent = fs.readFileSync(reportPath, 'utf8');
    const match = xmlContent.match(/line-rate="([\d.]+)"/);
    if (match) {
      return Math.round(parseFloat(match[1]) * 100);
    }
    return null;
  }
};

function main() {
  const readmePath = path.join(__dirname, '../README.md');
  if (!fs.existsSync(readmePath)) {
    console.error('Error: README.md not found');
    process.exit(1);
  }

  let readmeContent = fs.readFileSync(readmePath, 'utf8');
  let updatedCount = 0;

  for (const [service, parseFn] of Object.entries(parsers)) {
    let percentage = null;
    
    try {
      percentage = parseFn();
    } catch (err) {
      console.warn(`Warning parsing ${service} coverage: ${err.message}`);
    }

    // Fallback: If no report file exists, read existing percentage from README
    if (percentage === null) {
      const regex = new RegExp(`<!-- cov:${service} -->.*?${service}-(\\d+)%25.*?<!-- cov:${service}-end -->`);
      const match = readmeContent.match(regex);
      if (match) {
        percentage = parseInt(match[1], 10);
        console.log(`ℹ Preserved existing coverage for ${service}: ${percentage}%`);
      }
    }

    if (percentage !== null) {
      const badgeMarkdown = generateBadgeMarkdown(service, percentage);
      const regex = new RegExp(`(<!-- cov:${service} -->)(.*?)(<!-- cov:${service}-end -->)`, 'g');
      readmeContent = readmeContent.replace(regex, `$1${badgeMarkdown}$3`);
      updatedCount++;
    } else {
      console.log(`ℹ No coverage data or cached badge found for ${service}. Left as pending.`);
    }
  }

  fs.writeFileSync(readmePath, readmeContent, 'utf8');
  console.log(`Done! Updated README.md coverage badges for ${updatedCount} services.`);
}

main();
